const DICTS: Record<Lang, Dict> = { tr, en };
const STORAGE_KEY = "nibble.lang";

let current: Lang = "tr";
const listeners = new Set<() => void>();

function detect(): Lang {
  if (typeof window === "undefined") return "tr";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "tr" || saved === "en") return saved;
  } catch {
    /* özel mod */
  }
  const nav = navigator.language?.toLowerCase() ?? "";
  return nav.startsWith("tr") ? "tr" : "en";
}

let initialised = false;
function ensureInit() {
  if (initialised || typeof window === "undefined") return;
  initialised = true;
  current = detect();
  document.documentElement.lang = current;
}

export function getLang(): Lang {
  ensureInit();
  return current;
}

export function setLang(lang: Lang) {
  ensureInit();
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* özel mod */
  }
  document.documentElement.lang = lang;
  for (const fn of listeners) fn();
}

function subscribe(fn: () => void) {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/**
 * Sunucu anlık görüntüsü sabit "tr": statik export sırasında localStorage yok.
 * İstemci ilk render'dan sonra gerçek dile geçer (useSyncExternalStore'un
 * hidrasyon sözleşmesi bunu güvenle yapar).
 */
const serverSnapshot = () => "tr" as Lang;

/** Aktif dilin sözlüğü. Kullanım: const t = useT(); t.palette.title */
export function useT(): Dict {
  const lang = useSyncExternalStore(subscribe, getLang, serverSnapshot);
  return DICTS[lang];
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, serverSnapshot);
}

/** React dışından (ör. ajan API'si) mesaj almak için */
export function t(): Dict {
  return DICTS[getLang()];
}
